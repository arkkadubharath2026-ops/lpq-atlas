"""Writes the policy file in the exact format ``QueueSelectionPolicy::load`` reads,
and a JSON report with the evaluation and full provenance.

Policy file (one candidate line per trained width, ascending)::

    lpqpolicy 1
    margin <m>
    trained_on <single line of provenance>
    features log2_max_w log2_mean_w p50_over_max p99_over_max cv_w log2_nodes mean_degree
    candidate pooled w=<W> intercept <b> coef <c0> ... <c6>

Floats are written with ``repr`` (shortest string that round-trips a double), so the
C++ ``operator>>`` recovers the exact value.  Neither file is ever overwritten.
"""

from __future__ import annotations

import datetime as _dt
import json
import math
import platform
import subprocess
import sys
from pathlib import Path
from typing import Any

import numpy as np

from lpq_tools.policy.dataset import GraphInfo, PolicyTable, sha256_file
from lpq_tools.policy.profile import FEATURE_NAMES, PolicyFormatError, QueuePolicy, parse_policy_text
from lpq_tools.policy.train import FittedPolicy, TrainConfig

REPORT_FORMAT = "lpq-queue-policy-report/1"


def check_writable(*paths: Path) -> None:
    for p in paths:
        if p.exists():
            raise FileExistsError(f"refusing to overwrite existing file: {p}")


def git_state(cwd: Path | None = None) -> dict[str, Any]:
    """Commit hash and dirtiness if ``git`` is available here; otherwise nulls."""
    try:
        rev = subprocess.run(["git", "rev-parse", "HEAD"], cwd=cwd, capture_output=True,
                             text=True, timeout=10, check=True).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain"], cwd=cwd, capture_output=True,
                                    text=True, timeout=30, check=True).stdout.strip())
        return {"commit": rev, "dirty": dirty}
    except (OSError, subprocess.SubprocessError):
        return {"commit": None, "dirty": None}


def _num(x: float) -> str:
    if not math.isfinite(x):
        raise PolicyFormatError(f"non-finite value {x!r} cannot be written to a policy file")
    return repr(float(x))


def trained_on_line(fitted: FittedPolicy, seed: int, git_commit: str | None) -> str:
    parts = [
        f"datasets={','.join(fitted.datasets)}",
        f"algorithm={fitted.algorithm}",
        f"graphs={fitted.n_graphs}",
        f"topologies={fitted.n_topologies}",
        f"seed={seed}",
        f"lambda={fitted.hyper.lam:g}",
        f"features={'all' if fitted.feature_subset == FEATURE_NAMES else '+'.join(fitted.feature_subset)}",
        f"git={git_commit or 'unavailable'}",
    ]
    return " ".join(parts)


def format_policy(policy: QueuePolicy, trained_on: str) -> str:
    if "\n" in trained_on or "\r" in trained_on:
        raise PolicyFormatError("trained_on must be a single line")
    lines = [
        "lpqpolicy 1",
        "# Generated by lpq_tools.policy; see the sibling .report.json for the evaluation.",
        f"margin {_num(policy.margin)}",
        f"trained_on {trained_on}",
        "features " + " ".join(FEATURE_NAMES),
    ]
    for c in policy.candidates:
        lines.append(f"candidate pooled w={c.width} intercept {_num(c.intercept)} coef "
                     + " ".join(_num(v) for v in c.coef))
    text = "\n".join(lines) + "\n"
    parse_policy_text(text, "<generated>")  # the writer must be able to read its own output
    return text


def _clean(obj: Any) -> Any:
    """JSON-safe: non-finite floats become null, tuples lists, numpy scalars Python."""
    if isinstance(obj, dict):
        return {str(k): _clean(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_clean(v) for v in obj]
    if isinstance(obj, np.generic):
        return _clean(obj.item())
    if isinstance(obj, float):
        return obj if math.isfinite(obj) else None
    return obj


def export(
    out: Path,
    report: Path,
    *,
    fitted: FittedPolicy,
    evaluation: dict[str, Any],
    table: PolicyTable,
    infos: dict[str, GraphInfo],
    cfg: TrainConfig,
    seed: int,
) -> None:
    check_writable(out, report)
    git = git_state()
    text = format_policy(fitted.policy, trained_on_line(fitted, seed, git["commit"]))
    out.parent.mkdir(parents=True, exist_ok=True)
    report.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "x", encoding="ascii") as f:
        f.write(text)

    used = set(fitted.datasets)
    doc = {
        "format": REPORT_FORMAT,
        "generated_at": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        "policy_file": {"path": str(out), "sha256": sha256_file(out),
                        "margin": fitted.policy.margin,
                        "candidates": [{"width": c.width, "intercept": c.intercept,
                                        "coef": dict(zip(FEATURE_NAMES, c.coef))}
                                       for c in fitted.policy.candidates]},
        "provenance": {
            "git": git, "seed": seed, "python": platform.python_version(),
            "numpy": np.__version__, "argv": sys.argv,
            "result_files": [{"path": i.path, "sha256": i.sha256, "experiment_id": i.experiment_id,
                              "records": i.records} for i in table.inputs],
            "profiles": [{"dataset": ds, "path": gi.profile_path,
                          "sha256": sha256_file(gi.profile_path),
                          "topology": gi.topology, "declared_base": gi.base}
                         for ds, gi in sorted(infos.items()) if ds in used],
            "metadata": [{"dataset": ds, "path": gi.metadata_path,
                          "sha256": sha256_file(gi.metadata_path)}
                         for ds, gi in sorted(infos.items()) if ds in used],
            "datasets_with_inferred_id": table.inferred_datasets,
        },
        "training": {
            "algorithm": fitted.algorithm, "n_graphs": fitted.n_graphs,
            "n_topologies": fitted.n_topologies, "datasets": fitted.datasets,
            "feature_subset": list(fitted.feature_subset),
            "ridge_lambda": fitted.hyper.lam, "margin": fitted.hyper.margin,
            "inner_cv_folds": fitted.hyper.inner_folds,
            "inner_mse_by_lambda": {f"{k:g}": v for k, v in fitted.hyper.inner_mse_by_lambda.items()},
            "inner_mean_log_realised_ratio_by_margin": {
                f"{k:g}": v for k, v in fitted.hyper.inner_objective_by_margin.items()},
            "graphs_per_trained_width": fitted.per_width_graphs,
            "widths_not_trained_too_few_graphs": fitted.skipped_widths,
        },
        "evaluation": evaluation,
        "data_accounting": {
            "per_dataset_algorithm_width": table.count_report(),
            "ignored_non_candidate_records": [
                {"dataset": d, "algorithm": a, "label": lab, "records": n}
                for (d, a, lab), n in sorted(table.ignored.items())],
            "bootstrap_replicates": table.bootstrap_replicates,
            "labels": [{"dataset": r.dataset, "algorithm": r.algorithm, "width": r.width,
                        "labels": list(r.labels), "ring_sizes": list(r.ring_sizes),
                        "log_geo_mean_ratio": r.y, "ratio": r.ratio,
                        "bootstrap_se_log": r.se, "n_queries": r.n_queries,
                        "n_pairs": r.n_pairs, "files": list(r.files)} for r in table.rows],
        },
    }
    with open(report, "x", encoding="utf-8") as f:
        json.dump(_clean(doc), f, indent=2, allow_nan=False)
        f.write("\n")
