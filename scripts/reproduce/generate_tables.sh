#!/usr/bin/env bash
# =============================================================================
# Regenerate the tables the findings are stated in (ESD.md section 36).
#
#   scripts/reproduce/generate_tables.sh
#
# Reads results/raw/ and writes results/tables/. It never runs an experiment: if
# a results file is missing or incomplete the script stops and says which one,
# because a table built from a partial matrix is a partial result presented as a
# whole and nothing about its appearance says so.
#
# Every table carries its provenance -- the results file, the experiment id and
# the seed -- so a number lifted out of one can be traced back.
# =============================================================================
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

require_python

TABLES_DIR="${REPO_ROOT}/results/tables"
mkdir -p "$TABLES_DIR"

ablation="${RESULTS_DIR}/dimacs_ny_ablation_v1.json"
require_file "$ablation" "the ablation results" \
    "scripts/reproduce/run_main_experiments.sh"
require_complete_results "$ablation" binary_heap radix_heap lpq lpq_model

say "ablation waterfall"
"$PYTHON" - "$(native_path "$ablation")" "$(native_path "${TABLES_DIR}/ablation_waterfall.txt")" <<'PYEOF' ||
import sys
from lpq_tools.evaluation.ablation import build_waterfall, format_waterfall
from lpq_tools.evaluation.results import read_results

source, destination = sys.argv[1], sys.argv[2]
results = read_results(source)
rendered = format_waterfall(build_waterfall(results))

header = (
    f"# regenerated by scripts/reproduce/generate_tables.sh\n"
    f"# source     : {source}\n"
    f"# experiment : {results.experiment_id}\n"
    f"# generated  : {results.generated_at}\n\n"
)
open(destination, "w", encoding="utf-8").write(header + rendered + "\n")
print(rendered)
PYEOF
    die "building the ablation table failed"

say "paired comparisons across the ladder"
"$PYTHON" - "$(native_path "$ablation")" "$(native_path "${TABLES_DIR}/paired_comparisons.txt")" "$STATS_SEED" <<'PYEOF' ||
import sys
from lpq_tools.evaluation.results import read_results
from lpq_tools.statistics.comparison import adjust_comparisons, compare_paired

source, destination, seed = sys.argv[1], sys.argv[2], int(sys.argv[3])
results = read_results(source)

# The ladder as pairs: each comparison isolates one added component.
STEPS = [
    ("binary_heap", "radix_heap"),
    ("radix_heap", "lpq"),
    ("lpq", "lpq_model"),
]

comparisons = []
for a, b in STEPS:
    left, right = results.paired_medians(a, b)
    comparisons.append(compare_paired(left, right, name_a=a, name_b=b, seed=seed))

lines = [
    f"# regenerated by scripts/reproduce/generate_tables.sh",
    f"# source     : {source}",
    f"# experiment : {results.experiment_id}",
    f"# seed       : {seed}",
    "",
    "paired permutation test, Holm-corrected across the ladder.",
    "A NEGATIVE median difference means the added component made things slower.",
    "",
    f"{'step':<28} {'median diff ns':>16} {'95% CI':>30} {'B faster':>9} {'adj p':>10}",
    f"{'-' * 28} {'-' * 16} {'-' * 30} {'-' * 9} {'-' * 10}",
]
for c in adjust_comparisons(comparisons):
    interval = f"[{c.difference_ci.low:>13,.0f}, {c.difference_ci.high:>13,.0f}]"
    lines.append(
        f"{c.name_a + ' -> ' + c.name_b:<28} {c.median_difference:>16,.0f} "
        f"{interval:>30} {c.fraction_b_faster:>8.0%} {c.adjusted_p_value:>10.2e}"
    )

lines += [
    "",
    "  Timings are measurements and carry noise; the comparison counts in the",
    "  waterfall table are exact. A confidence interval that excludes zero is",
    "  evidence of an effect, not of its magnitude being reproducible on another",
    "  machine -- and matrix position was measured to inflate one of these",
    "  effects by 45% (docs/experiments/ablation-waterfall.md).",
]

rendered = "\n".join(lines)
open(destination, "w", encoding="utf-8").write(rendered + "\n")
print(rendered)
PYEOF
    die "building the paired comparison table failed"

say "model training reports"
for dataset in "${MAIN_DATASETS[@]}"; do
    report="${MODELS_DIR}/exported/${dataset}_static.report.json"
    if [ ! -f "$report" ]; then
        # Not fatal: the tables above stand without it, and saying which step
        # produces it is more useful than refusing to write anything.
        printf "    %s: no training report (run run_main_experiments.sh)\n" "$dataset"
        continue
    fi
    "$PYTHON" - "$(native_path "$report")" "$(native_path "${TABLES_DIR}/${dataset}_training.txt")" <<'PYEOF' ||
import json, sys

source, destination = sys.argv[1], sys.argv[2]
r = json.loads(open(source, encoding="utf-8").read())

lift = r["average_precision"] / r["average_precision_baseline"]
lines = [
    "# regenerated by scripts/reproduce/generate_tables.sh",
    f"# source : {source}",
    "",
    f"dataset            : {r['dataset_id']}",
    f"bucket width       : {r['bucket_width']}",
    f"queries            : {r['query_count']}  seed {r['query_seed']}",
    f"nodes              : {r['nodes']:,}",
    f"observations       : {r['observations']:,}",
    f"positives          : {r['positives']:,}  (rate {r['positive_rate']:.6f})",
    f"held out           : {r['test_fraction']:.0%} of nodes",
    "",
    f"held-out ROC AUC   : {r['roc_auc']:.6f}   (0.5 is chance)",
    f"in-sample ROC AUC  : {r['train_roc_auc']:.6f}",
    f"average precision  : {r['average_precision']:.6f}"
    f"   (chance {r['average_precision_baseline']:.6f})",
    f"precision lift     : {lift:.2f}x over a random ranker",
    f"accuracy           : {r['accuracy']:.6f}",
    f"  always-no gives  : {r['majority_baseline_accuracy']:.6f}",
    "",
    "  Accuracy is reported only beside its baseline. On this task the labels",
    "  are severely unbalanced, so accuracy alone flatters any model.",
]
open(destination, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"    {destination}")
PYEOF
        die "building the training table for ${dataset} failed"
done

say "generate_tables: complete"
say "tables in ${TABLES_DIR}"
